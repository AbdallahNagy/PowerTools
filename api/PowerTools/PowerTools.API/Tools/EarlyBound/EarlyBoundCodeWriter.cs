using System.Globalization;
using System.Text;

namespace PowerTools.API.Tools.EarlyBound;

/// <summary>
/// Writes early-bound C# classes for Dataverse tables. The output compiles
/// with C# 7.3 so it works in .NET Framework plug-in projects too.
/// </summary>
public static class EarlyBoundCodeWriter
{
    public const string DefaultNamespace = "Dataverse.Model";

    // Members of Microsoft.Xrm.Sdk.Entity and of each generated class.
    // A column with one of these names gets an "Attribute" suffix.
    private static readonly HashSet<string> ReservedMembers = new(StringComparer.Ordinal)
    {
        "Fields", "EntityLogicalName", "Id", "LogicalName", "Attributes", "FormattedValues",
        "RelatedEntities", "KeyAttributes", "RowVersion", "EntityState", "ExtensionData",
        "Item", "HasLazyFileAttribute", "LazyFileAttributeKey", "LazyFileAttributeValue",
        "LazyFileSizeAttributeKey", "LazyFileSizeAttributeValue",
    };

    private static readonly HashSet<string> CSharpKeywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
        "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else",
        "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
        "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
        "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed",
        "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this",
        "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    };

    public static bool IsValidNamespace(string value) =>
        value.Split('.').All(part => part.Length > 0 && Identifier(part) == part && !CSharpKeywords.Contains(part));

    public static string Write(string ns, IEnumerable<EarlyBoundTable> tables)
    {
        var sorted = tables
            .OrderBy(table => table.SchemaName, StringComparer.OrdinalIgnoreCase)
            .ToList();
        var typeNames = new HashSet<string>(StringComparer.Ordinal);
        var classes = sorted.Select(table => Unique(TypeName(table.SchemaName), typeNames)).ToList();

        var code = new CodeBuilder();
        code.Line("//------------------------------------------------------------------------------");
        code.Line("// <auto-generated>");
        code.Line("//     Generated by Power Tools Early Bound Generator.");
        code.Line("//     Changes to this file are lost when the code is generated again.");
        code.Line("// </auto-generated>");
        code.Line("//------------------------------------------------------------------------------");
        code.Line();
        code.Line("using System;");
        code.Line("using Microsoft.Xrm.Sdk;");
        code.Line();
        code.Line("[assembly: Microsoft.Xrm.Sdk.Client.ProxyTypesAssemblyAttribute()]");
        code.Line();
        code.Line($"namespace {ns}");
        code.Open();
        for (var index = 0; index < sorted.Count; index++)
        {
            if (index > 0) code.Line();
            WriteTable(code, sorted[index], classes[index], typeNames);
        }
        code.Close();
        return code.ToString();
    }

    private static void WriteTable(CodeBuilder code, EarlyBoundTable table, string className, HashSet<string> typeNames)
    {
        var columns = table.Columns
            .OrderBy(column => column.SchemaName, StringComparer.OrdinalIgnoreCase)
            .ToList();
        var memberNames = new HashSet<string>(ReservedMembers, StringComparer.Ordinal) { className };
        var properties = columns.Select(column => UniqueMember(Identifier(column.SchemaName), memberNames)).ToList();
        var enums = new List<(string Name, EarlyBoundColumn Column)>();

        Summary(code, table.DisplayName);
        code.Line($"[Microsoft.Xrm.Sdk.Client.EntityLogicalNameAttribute({Literal(table.LogicalName)})]");
        code.Line($"public partial class {className} : Entity");
        code.Open();
        code.Line($"public const string EntityLogicalName = {Literal(table.LogicalName)};");
        code.Line();
        code.Line("/// <summary>Logical names of the columns, for queries and column sets.</summary>");
        code.Line("public static class Fields");
        code.Open();
        for (var index = 0; index < columns.Count; index++)
            code.Line($"public const string {properties[index]} = {Literal(columns[index].LogicalName)};");
        code.Close();
        code.Line();
        code.Line($"public {className}() : base(EntityLogicalName) {{ }}");

        for (var index = 0; index < columns.Count; index++)
        {
            var column = columns[index];
            string? enumName = null;
            if (column.Kind is EarlyBoundColumnKind.Choice or EarlyBoundColumnKind.Choices
                && column.Options is { Count: > 0 })
            {
                enumName = Unique($"{className}_{properties[index]}", typeNames);
                enums.Add((enumName, column));
            }

            code.Line();
            WriteProperty(code, column, properties[index], enumName);
        }
        code.Close();

        foreach (var (name, column) in enums)
        {
            code.Line();
            WriteEnum(code, name, column);
        }
    }

    private static void WriteProperty(CodeBuilder code, EarlyBoundColumn column, string name, string? enumName)
    {
        var key = Literal(column.LogicalName);
        Summary(code, column.DisplayName);
        code.Line($"[AttributeLogicalName({key})]");

        if (column.Kind == EarlyBoundColumnKind.Choice && enumName is not null)
        {
            code.Line($"public {enumName}? {name}");
            code.Open();
            code.Line("get");
            code.Open();
            code.Line($"var option = GetAttributeValue<OptionSetValue>({key});");
            code.Line($"return option == null ? ({enumName}?)null : ({enumName})option.Value;");
            code.Close();
            if (!column.IsReadOnly)
                code.Line($"set {{ SetAttributeValue({key}, value.HasValue ? new OptionSetValue((int)value.Value) : null); }}");
            code.Close();
            return;
        }

        var type = ClrType(column.Kind);
        code.Line($"public {type} {name}");
        code.Open();
        code.Line($"get {{ return GetAttributeValue<{type}>({key}); }}");
        if (column.IsPrimaryId && column.Kind == EarlyBoundColumnKind.Guid)
        {
            code.Line("set");
            code.Open();
            code.Line($"SetAttributeValue({key}, value);");
            code.Line("base.Id = value ?? Guid.Empty;");
            code.Close();
        }
        else if (!column.IsReadOnly)
        {
            code.Line($"set {{ SetAttributeValue({key}, value); }}");
        }
        code.Close();
    }

    private static void WriteEnum(CodeBuilder code, string name, EarlyBoundColumn column)
    {
        var members = new HashSet<string>(StringComparer.Ordinal);
        Summary(code, column.DisplayName);
        code.Line($"public enum {name}");
        code.Open();
        foreach (var option in column.Options!.OrderBy(option => option.Value))
        {
            var member = MemberName(option.Label);
            if (member.Length == 0) member = $"Value{Number(option.Value)}";
            if (!members.Add(member))
            {
                member = $"{member}_{Number(option.Value)}";
                members.Add(member);
            }
            code.Line($"{member} = {option.Value.ToString(CultureInfo.InvariantCulture)},");
        }
        code.Close();
    }

    private static string ClrType(EarlyBoundColumnKind kind) => kind switch
    {
        EarlyBoundColumnKind.String => "string",
        EarlyBoundColumnKind.Integer => "int?",
        EarlyBoundColumnKind.BigInt => "long?",
        EarlyBoundColumnKind.Decimal => "decimal?",
        EarlyBoundColumnKind.Double => "double?",
        EarlyBoundColumnKind.Money => "Money",
        EarlyBoundColumnKind.Boolean => "bool?",
        EarlyBoundColumnKind.DateTime => "DateTime?",
        EarlyBoundColumnKind.Guid => "Guid?",
        EarlyBoundColumnKind.Lookup => "EntityReference",
        EarlyBoundColumnKind.Choice => "OptionSetValue",
        EarlyBoundColumnKind.Choices => "OptionSetValueCollection",
        EarlyBoundColumnKind.PartyList => "EntityCollection",
        EarlyBoundColumnKind.Image => "byte[]",
        _ => "object",
    };

    private static void Summary(CodeBuilder code, string text)
    {
        var line = text.ReplaceLineEndings(" ").Trim();
        if (line.Length == 0) return;
        code.Line($"/// <summary>{System.Security.SecurityElement.Escape(line)}</summary>");
    }

    /// <summary>Turns any text into a valid C# identifier without changing valid ones.</summary>
    private static string Identifier(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
            builder.Append(char.IsAsciiLetterOrDigit(ch) || ch == '_' ? ch : '_');
        if (builder.Length == 0 || char.IsAsciiDigit(builder[0])) builder.Insert(0, '_');
        return builder.ToString();
    }

    private static string TypeName(string schemaName)
    {
        var name = Identifier(schemaName);
        return CSharpKeywords.Contains(name) ? $"{name}_" : name;
    }

    private static string UniqueMember(string name, HashSet<string> taken)
    {
        if (CSharpKeywords.Contains(name) || taken.Contains(name)) name = $"{name}Attribute";
        return Unique(name, taken);
    }

    private static string Unique(string name, HashSet<string> taken)
    {
        var candidate = name;
        for (var suffix = 2; !taken.Add(candidate); suffix++)
            candidate = $"{name}{suffix}";
        return candidate;
    }

    /// <summary>"Not started (old)" becomes NotStartedOld.</summary>
    private static string MemberName(string label)
    {
        var builder = new StringBuilder();
        var startWord = true;
        foreach (var ch in label)
        {
            if (!char.IsAsciiLetterOrDigit(ch))
            {
                startWord = true;
                continue;
            }
            builder.Append(startWord ? char.ToUpperInvariant(ch) : ch);
            startWord = false;
        }
        if (builder.Length > 0 && char.IsAsciiDigit(builder[0])) builder.Insert(0, '_');
        return builder.ToString();
    }

    private static string Number(int value) =>
        value < 0 ? $"Minus{(-(long)value).ToString(CultureInfo.InvariantCulture)}" : value.ToString(CultureInfo.InvariantCulture);

    private static string Literal(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private sealed class CodeBuilder
    {
        private readonly StringBuilder text = new();
        private int depth;

        public void Line(string line = "")
        {
            if (line.Length > 0) text.Append(' ', depth * 4).Append(line);
            text.Append('\n');
        }

        public void Open()
        {
            Line("{");
            depth++;
        }

        public void Close()
        {
            depth--;
            Line("}");
        }

        public override string ToString() => text.ToString();
    }
}
