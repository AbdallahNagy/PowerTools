// Writes the README tool table from the public tool catalog.
//
// Source of truth: PUBLIC_TOOLS in desktop/src/ui/tools/publicCatalog.ts
// Generated: the table between the tools markers in README.md
//
// Usage:
//   node scripts/sync-readme-tools.mjs          update README.md
//   node scripts/sync-readme-tools.mjs --check  exit 1 if README.md is stale

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const readmePath = join(root, "README.md");
const catalogPath = join(root, "desktop", "src", "ui", "tools", "publicCatalog.ts");

export const START_MARKER = "<!-- tools:start (generated by scripts/sync-readme-tools.mjs from desktop/src/ui/tools/publicCatalog.ts) -->";
export const END_MARKER = "<!-- tools:end -->";

const escapeCell = (text) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

/** The Markdown table for the given tools, in catalog order. */
export function renderToolTable(tools) {
  const rows = tools.map(
    (tool) => `| [${escapeCell(tool.title)}](desktop/src/ui/tools/${tool.id}/) | ${escapeCell(tool.description)} |`,
  );
  return ["| Tool | What you can do |", "| --- | --- |", ...rows].join("\n");
}

/** The generated table currently in the README, or undefined if the markers are missing. */
export function readToolTable(readme) {
  const text = readme.replace(/\r\n/g, "\n");
  const start = text.indexOf(START_MARKER);
  const end = text.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) return undefined;
  return text.slice(start + START_MARKER.length, end).trim();
}

export function replaceToolTable(readme, table) {
  const text = readme.replace(/\r\n/g, "\n");
  const start = text.indexOf(START_MARKER);
  const end = text.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`README.md needs "${START_MARKER}" and "${END_MARKER}" around the tool table.`);
  }
  return `${text.slice(0, start + START_MARKER.length)}\n\n${table}\n\n${text.slice(end)}`;
}

async function main() {
  const { PUBLIC_TOOLS } = await import(pathToFileURL(catalogPath).href);
  const readme = readFileSync(readmePath, "utf8");
  const next = replaceToolTable(readme, renderToolTable(PUBLIC_TOOLS));

  if (process.argv.includes("--check")) {
    if (next !== readme.replace(/\r\n/g, "\n")) {
      console.error("README.md tool table is out of date. Run: node scripts/sync-readme-tools.mjs");
      return 1;
    }
    console.log("README.md tool table matches the public catalog.");
    return 0;
  }

  writeFileSync(readmePath, next);
  console.log(`README.md lists ${PUBLIC_TOOLS.length} tools.`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main();
}
